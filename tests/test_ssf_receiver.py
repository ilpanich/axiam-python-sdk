def serve_jwks(router: respx.MockRouter, *keys: Key) -> respx.Route:
    """Serve ``keys`` at the JWKS URL; the route counts the fetches."""
    return router.get(JWKS).mock(
        return_value=httpx.Response(200, json={"keys": [k.jwk() for k in keys]})
    )


def receiver(**overrides: Any) -> SsfReceiver:
    """A receiver over a fresh client, with a run-time poll bearer."""
    token = f"cc-{secrets.token_urlsafe(16)}"
    options: dict[str, Any] = {
        "issuer": ISSUER,
        "audience": AUDIENCE,
        "jwks_uri": JWKS,
        "access_token_provider": lambda: SecretStr(token),
    }
    options.update(overrides)
    return SsfReceiver(AxiamClient(base_url=BASE, tenant_slug="acme"), **options)


def reason(r: SsfReceiver, set_token: str) -> SetFailureReason:
    """The refusal's reason; it is an ``AuthError``."""
    with pytest.raises(SetVerificationError) as excinfo:
        r.verify_set(set_token)
    assert isinstance(excinfo.value, AuthError)
    assert excinfo.value.reason == excinfo.value.set_failure_reason.value
    return excinfo.value.set_failure_reason


