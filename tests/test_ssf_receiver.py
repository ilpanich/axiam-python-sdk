def test_an_unknown_kid_costs_one_refetch_and_a_second_one_none(router: respx.MockRouter) -> None:
    """Prime (1), unknown kid -> 2, another unknown kid within the minute -> 2."""
    key = Key()
    jwks = serve_jwks(router, key)
    now = [1000.0]
    r = receiver(clock=lambda: now[0])
    r.verify_set(key.sign_set(claims()))
    assert jwks.call_count == 1
    assert reason(r, Key().sign_set(claims())) is SetFailureReason.INVALID_KEY
    assert jwks.call_count == 2, "exactly one refetch"
    assert reason(r, Key().sign_set(claims())) is SetFailureReason.INVALID_KEY
    assert jwks.call_count == 2, "no refetch within the minute"
    now[0] += 61
    assert reason(r, Key().sign_set(claims())) is SetFailureReason.INVALID_KEY
    assert jwks.call_count == 3, "a minute later, one more"
    now[0] += 400
    r.verify_set(key.sign_set(claims()))
    assert jwks.call_count == 4, "past its lifespan the JWKS is fetched again"


