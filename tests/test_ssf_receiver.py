def test_a_set_signed_by_the_jwks_key_verifies_into_its_claims(router: respx.MockRouter) -> None:
    """Every field of the result is the claim's; array ``aud`` and the media type too."""
    key = Key()
    serve_jwks(router, key)
    c = claims()
    event = receiver().verify_set(key.sign_set(c))
    assert event.jti == c["jti"]
    assert event.iat == 1_791_500_000
    assert event.iss == ISSUER
    assert event.aud == AUDIENCE
    assert event.txn == "t-1"
    assert event.event_type == SESSION_REVOKED
    assert event.event == c["events"][SESSION_REVOKED]
    assert event.sub_id == c["sub_id"]

    array = claims(aud=["other", AUDIENCE])
    header = {"alg": "EdDSA", "typ": "Application/SecEvent+JWT", "kid": key.kid}
    assert receiver().verify_set(key.sign(header, array)).aud == ["other", AUDIENCE]


