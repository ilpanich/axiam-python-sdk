def test_a_wrong_typ_or_alg_is_refused_in_that_order(router: respx.MockRouter) -> None:
    """``typ`` absent or ``JWT`` -> invalid_type; ``none`` / ``HS256`` -> invalid_key."""
    key = Key()
    serve_jwks(router, key)
    r = receiver()
    c = claims()
    for header in (
        {"alg": "EdDSA", "kid": key.kid},
        {"alg": "EdDSA", "typ": "JWT", "kid": key.kid},
    ):
        assert reason(r, key.sign(header, c)) is SetFailureReason.INVALID_TYPE
    payload = b64(json.dumps(c).encode())
    none = f"{b64(json.dumps({'alg': 'none', 'typ': 'secevent+jwt'}).encode())}.{payload}."
    assert reason(r, none) is SetFailureReason.INVALID_KEY
    import jwt as pyjwt

    hs = pyjwt.encode(
        c,
        secrets.token_bytes(32),
        algorithm="HS256",
        headers={"typ": "secevent+jwt", "kid": key.kid},
    )
    assert reason(r, hs) is SetFailureReason.INVALID_KEY
    no_kid = key.sign({"alg": "EdDSA", "typ": "secevent+jwt"}, c)
    assert reason(r, no_kid) is SetFailureReason.INVALID_KEY
    for malformed in ("a.b", "!!.@@.##", f"!!.{payload}.c2ln", f"{payload}.@@.", "x.y.z!", 42):
        assert reason(r, malformed) is SetFailureReason.MALFORMED  # type: ignore[arg-type]
    array_header = f"{b64(b'[1]')}.{payload}.{b64(b'sig')}"
    assert reason(r, array_header) is SetFailureReason.MALFORMED


