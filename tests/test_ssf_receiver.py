@pytest.mark.asyncio
async def test_the_async_receiver_verifies_polls_and_refuses_alike(
    router: respx.MockRouter,
) -> None:
    """Verify, replay, unknown kid, poll (async provider), 400 not retried."""
    key = Key()
    jwks = serve_jwks(router, key)
    discovery = f"{BASE}/.well-known/ssf-configuration"
    router.get(discovery).mock(
        return_value=httpx.Response(200, json={"issuer": ISSUER, "jwks_uri": JWKS})
    )
    token = f"cc-{secrets.token_urlsafe(16)}"

    async def provider() -> str:
        """An async bearer source."""
        return token

    client = AsyncAxiamClient(base_url=BASE, tenant_slug="acme")
    r = AsyncSsfReceiver(
        client,
        issuer=ISSUER,
        audience=AUDIENCE,
        discovery_url=discovery,
        access_token_provider=provider,
    )
    assert "AsyncSsfReceiver" in repr(r)
    set_token = key.sign_set(claims())
    assert (await r.verify_set(set_token)).event_type == SESSION_REVOKED
    with pytest.raises(SetVerificationError) as replayed:
        await r.verify_set(set_token)
    assert replayed.value.set_failure_reason is SetFailureReason.REPLAYED
    with pytest.raises(SetVerificationError):
        await r.verify_set(Key().sign_set(claims()))
    assert jwks.call_count == 2

    good = claims()
    poll = router.post(f"{BASE}/ssf/v1/poll/s").mock(
        return_value=httpx.Response(
            200,
            json={
                "sets": {good["jti"]: key.sign_set(good), "x": None, "y": key.sign_set(claims())},
                "moreAvailable": False,
            },
        )
    )
    result = await r.poll("s", ack=["a"])
    assert [e.jti for e in result.events] == [good["jti"]]
    assert {x.reason for x in result.refused} == {
        SetFailureReason.MALFORMED,
        SetFailureReason.INVALID_REQUEST,
    }
    if poll.calls[0].request.headers["authorization"] != f"Bearer {token}":
        pytest.fail("the poll did not carry the provider's bearer")

    refused = router.post(f"{BASE}/ssf/v1/poll/bad").mock(return_value=httpx.Response(400))
    with pytest.raises(ValidationError):
        await r.poll("bad")
    assert refused.call_count == 1
    flaky = router.post(f"{BASE}/ssf/v1/poll/flaky").mock(
        side_effect=[
            httpx.ConnectError("reset"),
            httpx.Response(503),
            httpx.Response(200, json={"sets": {}}),
        ]
    )
    await r.poll("flaky")
    assert flaky.call_count == 3

    router.post(f"{BASE}/ssf/v1/poll/ok").mock(return_value=httpx.Response(200, json={}))
    sync_provider = AsyncSsfReceiver(
        client, issuer=ISSUER, audience=AUDIENCE, jwks_uri=JWKS, access_token_provider=lambda: token
    )
    assert (await sync_provider.poll("ok")).events == []
    with pytest.raises(AuthError):
        await AsyncSsfReceiver(client, issuer=ISSUER, audience=AUDIENCE, jwks_uri=JWKS).poll("s")
    with pytest.raises(ValidationError):
        AsyncSsfReceiver(
            client, issuer=ISSUER, audience=AUDIENCE, jwks_uri=JWKS, replay_window_seconds=1
        )
    router.routes.clear()
    router.get(JWKS).mock(side_effect=httpx.ConnectError("refused"))
    with pytest.raises(NetworkError):
        await AsyncSsfReceiver(client, issuer=ISSUER, audience=AUDIENCE, jwks_uri=JWKS).verify_set(
            key.sign_set(claims())
        )
    await client.aclose()
