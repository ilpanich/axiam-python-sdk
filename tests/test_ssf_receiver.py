def b64(data: bytes) -> str:
    """Unpadded base64url."""
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode()


class Key:
    """A fresh Ed25519 signing key with a random ``kid``."""

    def __init__(self, kid: str | None = None) -> None:
        """Generate the key."""
        self.kid = kid or f"k-{uuid.uuid4().hex}"
        self.private = Ed25519PrivateKey.generate()

    def jwk(self) -> dict[str, Any]:
        """The public JWK."""
        jwk = json.loads(OKPAlgorithm.to_jwk(self.private.public_key()))
        jwk.update({"kid": self.kid, "alg": "EdDSA", "use": "sig"})
        return dict(jwk)

    def sign(self, header: dict[str, Any], claims: dict[str, Any]) -> str:
        """A compact JWS over ``header`` and ``claims``."""
        signing_input = f"{b64(json.dumps(header).encode())}.{b64(json.dumps(claims).encode())}"
        return f"{signing_input}.{b64(self.private.sign(signing_input.encode()))}"

    def sign_set(self, claims: dict[str, Any]) -> str:
        """A SET with the transmitter's header."""
        return self.sign({"alg": "EdDSA", "typ": "secevent+jwt", "kid": self.kid}, claims)


def claims(**changes: Any) -> dict[str, Any]:
    """A valid SET claim set; ``None`` in ``changes`` removes a member."""
    body: dict[str, Any] = {
        "iss": ISSUER,
        "aud": AUDIENCE,
        "iat": 1_791_500_000,
        "jti": uuid.uuid4().hex,
        "txn": "t-1",
        "sub_id": {"format": "iss_sub", "iss": ISSUER, "sub": str(uuid.uuid4())},
        "events": {SESSION_REVOKED: {"event_timestamp": 1_791_500_000}},
    }
    for k, v in changes.items():
        if v is None:
            body.pop(k, None)
        else:
            body[k] = v
    return body


