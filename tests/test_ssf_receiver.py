def test_poll_passes_ack_and_set_errs_through_and_sorts_the_answer(
    router: respx.MockRouter,
) -> None:
    """Exact body, verified and refused apart, and ``{}`` with no options."""
    key = Key()
    serve_jwks(router, key)
    stream = str(uuid.uuid4())
    good, bad = claims(), claims(iss="https://impostor.test")
    mismatched = claims()
    reply = {
        "sets": {
            good["jti"]: key.sign_set(good),
            bad["jti"]: key.sign_set(bad),
            "not-its-jti": key.sign_set(mismatched),
            "not-a-string": 42,
        },
        "moreAvailable": True,
    }
    poll = router.post(f"{BASE}/ssf/v1/poll/{stream}").mock(
        return_value=httpx.Response(200, json=reply)
    )
    r = receiver()
    result = r.poll(
        stream,
        max_events=10,
        return_immediately=True,
        ack=["done-1", "done-2"],
        set_errs={"old-1": SetErr.from_reason(SetFailureReason.REPLAYED)},
    )
    assert result.more_available is True
    assert [e.jti for e in result.events] == [good["jti"]]
    refused = {x.jti: x.reason for x in result.refused}
    assert refused == {
        bad["jti"]: SetFailureReason.INVALID_ISSUER,
        "not-its-jti": SetFailureReason.INVALID_REQUEST,
        "not-a-string": SetFailureReason.MALFORMED,
    }
    request = poll.calls[0].request
    assert json.loads(request.content) == {
        "maxEvents": 10,
        "returnImmediately": True,
        "ack": ["done-1", "done-2"],
        "setErrs": {"old-1": {"err": "invalid_request"}},
    }, "exactly as given, and nothing acknowledged on the caller's behalf"
    if not request.headers["authorization"].startswith("Bearer cc-"):
        pytest.fail("the poll did not carry the provider's bearer")
    assert "cookie" not in request.headers

    router.routes.clear()
    second = router.post(f"{BASE}/ssf/v1/poll/{stream}").mock(
        return_value=httpx.Response(200, json={"sets": {}})
    )
    empty = r.poll(stream)
    assert json.loads(second.calls[0].request.content) == {}
    assert empty.events == [] and empty.refused == [] and empty.more_available is False


