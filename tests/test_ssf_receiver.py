def test_the_memory_store_forgets_after_the_window() -> None:
    """Atomic check-and-record with expiry."""
    now = [0.0]
    store = MemoryReplayStore(clock=lambda: now[0])
    assert store.check_and_record("a", 60)
    assert not store.check_and_record("a", 60)
    now[0] = 61.0
    assert store.check_and_record("a", 60), "expired, so new again"
    assert MIN_REPLAY_WINDOW_SECONDS == 7 * 24 * 60 * 60


