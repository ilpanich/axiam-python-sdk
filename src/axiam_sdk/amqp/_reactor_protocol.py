"""The reactor wire protocol — the signed event and the signed reply (§22.1–§22.4).

Mirror, never import. These shapes reproduce the field order and ``serde``
behaviour of the server's ``ReactorEventMessage`` / ``ReactorReply``
(``crates/axiam-amqp/src/reactor/protocol.rs``) byte-for-byte using only the
standard library. ``testdata/reactor_v2_reference_vectors.json`` — generated by
the server's own sign path — is what pins them.

Both directions are signed with the same §8 v2 primitives and the same tenant
subkey: the server signs the event, the reactor signs the reply. A reply is an
instruction to change a token or refuse a login, so an unsigned reply is not a
weak reply — it is not a reply at all, and the server discards it as though the
reactor had never answered.

Three ways to produce a MAC that never verifies, with no other symptom
=====================================================================

**1. ``hmac_signature`` is serialized as ``null``, not omitted.** §8's own two
message types (``AuthzRequest``, ``AuditEventMessage`` — see ``_hmac.py``) sign
a body with the field ABSENT. A reactor event and a reactor reply sign it
PRESENT and ``null``::

    {"correlation_id":"…","tenant_id":"…", … ,"hmac_signature":null}
                                                               ^^^^ present

**2. ``ensure_ascii`` must be off.** ``json.dumps`` escapes every non-ASCII
character into a ``\\uXXXX`` sequence by default; ``serde_json`` escapes none of
them and emits UTF-8 directly. A deny reason containing an accented character
would otherwise produce bytes the server never reconstructs, for a message that
was otherwise perfectly well formed.

**3. ``issued_at`` is chrono's RFC 3339, not Python's.**
``datetime.isoformat()`` renders UTC as ``+00:00`` and always carries six
fractional digits once ``microsecond`` is non-zero. The server's
``chrono::DateTime<Utc>`` serializes with ``SecondsFormat::AutoSi`` and a ``Z``
suffix: no fractional part at all on a whole second, otherwise three or six
digits. :func:`to_chrono_rfc3339` is the fix and it is not optional.

Everything else about §8 v2 is unchanged: the HKDF-derived per-tenant subkey,
HMAC-SHA256 hex-encoded and compared in constant time, ``key_version = 2`` as a
hard floor, a ±300 s freshness window checked in BOTH directions, and a fresh
UUIDv4 ``nonce`` inside the signed bytes.
"""

