def ruff_format(path: Path, source: str) -> str:
    """Run ``ruff format`` over generated ``source``, as ``gofmt`` would.

    CI runs ``ruff format --check .`` over the whole repository, so generated
    output has to satisfy the formatter exactly. Reproducing a formatter's line
    breaking inside an emitter is a losing game -- the response-body literals in
    the conformance suite alone would need most of one -- so the emitter aims for
    correct code and the formatter decides the layout. ``ruff`` is already a dev
    dependency, pinned in ``pyproject.toml``, and both this script and
    ``ruff format --check`` run in the same CI job off that pin.

    Raises:
        SystemExit: if ``ruff`` is not on PATH, or rejects the emitted source.
            Silently skipping would make ``--check`` depend on who ran it.
    """
    try:
        done = subprocess.run(
            ["ruff", "format", "--stdin-filename", str(path), "-"],
            input=source,
            capture_output=True,
            text=True,
            check=False,
        )
    except FileNotFoundError:
        raise SystemExit(
            "ruff is not on PATH; this generator formats its output with it. "
            "Install the dev extras: pip install -e '.[dev]'"
        ) from None
    if done.returncode != 0:
        raise SystemExit(f"ruff format rejected generated {path.name}:\n{done.stderr.strip()}")
    return done.stdout


def build() -> dict[Path, str]:
    """Every file this generator owns, mapped to its current content."""
    files: dict[Path, str] = {
        ROOT / "src/axiam_sdk/management/models.py": emit_models(),
        ROOT / "src/axiam_sdk/management/ops/__init__.py": emit_ops_index(),
        ROOT / "tests/test_management_surface_generated.py": emit_test(),
    }
    for ns, nsdef in REGISTRY["namespaces"].items():
        files[ROOT / f"src/axiam_sdk/management/ops/{ns}.py"] = emit_namespace(ns, nsdef)
    return {path: ruff_format(path, body) for path, body in files.items()}


def main() -> int:
    """Write the generated surface, or verify it is current under ``--check``."""
    files = build()
    if "--check" in sys.argv:
        stale = [
            path
            for path, body in files.items()
            if not path.exists()
            or path.read_text() != (body if body.endswith("\n") else body + "\n")
        ]
        if stale:
            for path in stale:
                print(f"FAIL: {path.relative_to(ROOT)} is stale", file=sys.stderr)
            print("run `python scripts/gen_management.py`", file=sys.stderr)
            return 1
        print(
            f"OK: {len(files)} generated files are current "
            f"({REGISTRY['operation_count']} operations)"
        )
        return 0
    for path, body in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body if body.endswith("\n") else body + "\n")
    print(
        f"wrote {len(files)} files: {REGISTRY['operation_count']} operations across "
        f"{REGISTRY['namespace_count']} namespaces"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
