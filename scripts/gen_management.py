def example_json(schema: Any, depth: int = 0) -> Any:
    """A minimal server response body satisfying ``schema``."""
    if depth > 6 or not schema:
        return None
    if "$ref" in schema:
        return example_json(resolve_ref(schema), depth + 1)
    inner = nullable_ref(schema)
    if inner:
        return example_json(SCHEMAS.get(inner, {}), depth + 1)
    if "enum" in schema:
        return schema["enum"][0]
    variants = schema.get("oneOf") or schema.get("anyOf")
    if variants:
        first = next((v for v in variants if v.get("type") != "null"), None)
        return example_json(first, depth + 1) if first else None
    if "allOf" in schema:
        merged: dict[str, Any] = {}
        for part in schema["allOf"]:
            got = example_json(part, depth + 1)
            if isinstance(got, dict):
                merged.update(got)
        return merged
    kind = schema.get("type")
    if isinstance(kind, list):
        kind = next((k for k in kind if k != "null"), None)
    if kind == "object" or (not kind and "properties" in schema):
        required = set(schema.get("required") or [])
        return {
            name: example_json(prop, depth + 1)
            for name, prop in (schema.get("properties") or {}).items()
            if name in required
        }
    if kind == "array":
        return []
    if kind in ("integer", "number"):
        return 1
    if kind == "boolean":
        return True
    if kind == "string":
        if schema.get("format") == "uuid":
            return EXAMPLE_UUID
        if schema.get("format") == "date-time":
            return EXAMPLE_TIME
        return "example"
    return {}


def example_response(op: dict[str, Any]) -> str:
    """A Python literal for the response body the conformance test mounts."""
    kind, schema = op["response"]["kind"], op["response"]["schema"]
    if kind == "none":
        return "None"
    # `repr`, not `json.dumps`: this literal is pasted into a Python test module,
    # where JSON's `true`/`null` are NameErrors.
    one = example_json(SCHEMAS.get(schema, {}))
    if kind == "array":
        return repr([one])
    if kind == "page":
        return repr({"items": [one], "total": 1, "offset": 0, "limit": 50})
    return repr(one)


def py_literal(schema: Any, secrets: set[str], fieldname: str | None = None, depth: int = 0) -> str:
    """A Python expression building a minimal valid value for ``schema``."""
    if depth > 6:
        return "None"
    if fieldname and fieldname in secrets:
        return 'SecretStr("example")'
    if "$ref" in schema:
        return literal_for(schema["$ref"].split("/")[-1], secrets, depth + 1)
    if nullable_ref(schema) or "oneOf" in schema or "anyOf" in schema:
        return "None"
    kind = schema.get("type")
    if isinstance(kind, list):
        if "null" in kind:
            return "None"
        kind = next(iter(kind), None)
    if "enum" in schema:
        return json.dumps(schema["enum"][0])
    if kind == "array":
        return "[]"
    if kind in ("integer", "number"):
        return "1"
    if kind == "boolean":
        return "True"
    if kind == "string":
        if schema.get("format") == "uuid":
            return f'"{EXAMPLE_UUID}"'
        if schema.get("format") == "date-time":
            return f'"{EXAMPLE_TIME}"'
        return '"example"'
    if kind == "object" or not schema:
        return "{}"
    return "None"


def literal_for(name: str, secrets: set[str], depth: int = 0) -> str:
    """A Python expression constructing a minimal valid ``name``."""
    schema = SCHEMAS.get(name, {})
    if "enum" in schema:
        return json.dumps(schema["enum"][0])
    union = discriminated(schema)
    if union:
        tag, arms = union
        value, payload = arms[0]
        arm = f"{pascal(name)}{pascal(value)}"
        if "$ref" in payload:
            props, required, _ = flatten(payload["$ref"].split("/")[-1])
        else:
            props = payload.get("properties") or {}
            required = set(payload.get("required") or [])
        parts = [f'{safe(tag)}="{value}"']
        parts += [
            f"{safe(p)}={py_literal(props[p], set(), p, depth + 1)}"
            for p in sorted(props)
            if p in required and p != tag
        ]
        return f"models.{arm}({', '.join(parts)})"
    if "oneOf" in schema:
        return "None"
    props, required, _ = flatten(name)
    own = secrets if depth == 0 else set()
    parts = [
        f"{safe(p)}={py_literal(props[p], own, p, depth + 1)}"
        for p in sorted(props)
        if p in required
    ]
    return f"models.{pascal(name)}({', '.join(parts)})"


def call_arguments(
    namespace: str, opname: str, op: dict[str, Any], secrets: dict[str, set[str]]
) -> tuple[list[str], str]:
    """The conformance test's positional arguments, and the route it mounts."""
    implicit = implicit_params(namespace, op)
    args: list[str] = []
    route = op["path"]
    for p in op["path_params"]:
        name = p["name"]
        if name in implicit:
            route = route.replace(f"{{{name}}}", "{ORG_ID}" if name == "org_id" else "{TENANT_ID}")
            continue
        if p.get("format") == "uuid":
            args.append("EXAMPLE_ID")
            route = route.replace(f"{{{name}}}", "{EXAMPLE_ID}")
        else:
            args.append('"example"')
            route = route.replace(f"{{{name}}}", "example")
    required_q, optional_q = split_query(op)
    args.extend('"example"' for _ in required_q)
    if op["request_body"] == "schema":
        args.append(literal_for(op["request_schema"], secrets.get(op["request_schema"], set())))
    elif op["request_body"] == "untyped":
        args.append("{}")
    if filter_name(namespace, opname, optional_q):
        args.append("None")
    else:
        args.extend("None" for _ in optional_q)
    if op["paginated"]:
        args.append("PageRequest(limit=50)")
    return args, route


