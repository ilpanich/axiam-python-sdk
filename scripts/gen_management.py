def pascal(text: str) -> str:
    """``service_accounts`` -> ``ServiceAccounts``, with the rename map applied."""
    parts = [p for p in text.replace("-", "_").replace(" ", "_").split("_") if p]
    joined = "".join(p[0].upper() + p[1:] for p in parts)
    return RENAMED_SCHEMAS.get(joined, joined)


def snake(text: str) -> str:
    """``ServiceAccounts`` -> ``service_accounts``; already-snake input is kept."""
    out: list[str] = []
    for i, ch in enumerate(text):
        boundary = not text[i - 1].isupper() or (i + 1 < len(text) and text[i + 1].islower())
        if ch.isupper() and i and boundary:
            out.append("_")
        out.append(ch.lower())
    return "".join(out).replace("-", "_").replace("__", "_")


def safe(name: str) -> str:
    """A Python-legal identifier for ``name``, keywords suffixed."""
    ident = snake(name)
    return f"{ident}_" if ident in PY_KEYWORDS else ident


def wrap(text: str, width: int = 76) -> list[str]:
    """Reflow ``text`` into paragraph-preserving lines; ruff does not reflow docstrings."""
    out: list[str] = []
    for para in str(text).strip().split("\n\n"):
        words = para.split()
        if not words:
            continue
        line = ""
        for word in words:
            if line and len(line) + 1 + len(word) > width:
                out.append(line)
                line = word
            else:
                line = f"{line} {word}" if line else word
        if line:
            out.append(line)
        out.append("")
    while out and out[-1] == "":
        out.pop()
    return out


def docstring(text: str, indent: str = "") -> list[str]:
    """A PEP 257 docstring block for ``text`` at ``indent``."""
    lines = wrap(text, 76 - len(indent))
    if not lines:
        return [f'{indent}"""Undocumented."""']
    if len(lines) == 1 and len(indent) + len(lines[0]) + 6 <= 96 and not lines[0].endswith('"'):
        return [f'{indent}"""{lines[0]}"""']
    body = [f'{indent}"""{lines[0]}']
    for line in lines[1:]:
        body.append(f"{indent}{line}" if line else "")
    body.append(f'{indent}"""')
    return body


def field_doc(text: str, indent: str = "    ") -> list[str]:
    """An attribute docstring, the Sphinx-recognised form for a field."""
    lines = wrap(text, 76 - len(indent))
    if not lines:
        return []
    if len(lines) == 1:
        return [f'{indent}"""{lines[0]}"""']
    rest = [f"{indent}{x}" if x else "" for x in lines[1:]]
    return [f'{indent}"""{lines[0]}', "", *rest, f'{indent}"""']


