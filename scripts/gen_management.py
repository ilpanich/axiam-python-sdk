MODELS_HEADER = '''"""Request and response types for the CONTRACT §27 management surface.

Three shapes recur and are worth knowing before reading:

- **Sparse update bodies.** Every field is optional, and a field you never set
  is *absent from the wire body* rather than sent as ``null`` -- so a body
  carrying one field changes one field (§27.4 rule 5). Setting a field to
  ``None`` explicitly is a different statement and does send ``null``.
- **Replacement bodies.** ``SetOrgSettings``, the organization email config,
  ``WebauthnAttestationPolicy`` and ``SetMtlsTrustAnchor`` have required fields,
  because a ``PUT`` on those routes replaces rather than patches. Pydantic
  refuses to build one half-filled, which is the point.
- **Types carrying a secret.** These hold a :class:`~pydantic.SecretStr`, so the
  value is redacted from every ``repr``, log line and JSON rendering; call
  ``.get_secret_value()`` to read it. :meth:`~axiam_sdk.management._wire.ManagementModel.to_wire`
  is the one place they are unwrapped for the socket.
"""
'''


def field_lines(
    name: str,
    schema: Any,
    *,
    required: bool,
    secret: bool,
) -> list[str]:
    """One model field: its annotation, default and attribute docstring."""
    annotation = "SecretStr" if secret else py_type(schema)
    ident = safe(name)
    alias = f'Field(alias="{name}")' if ident != name else None

    if required:
        default = f" = {alias}" if alias else ""
    elif annotation.endswith("| None"):
        default = f' = Field(default=None, alias="{name}")' if alias else " = None"
    else:
        annotation = f"{annotation} | None"
        default = f' = Field(default=None, alias="{name}")' if alias else " = None"

    text = schema.get("description") or f"``{name}``."
    if secret:
        text += (
            "\n\n**Secret.** Redacted from every string, log and JSON rendering; "
            "call ``.get_secret_value()`` to read it."
        )
    return [f"    {ident}: {annotation}{default}", *field_doc(text)]


def emit_model_class(
    class_name: str,
    props: dict[str, Any],
    required: set[str],
    description: str | None,
    secrets: set[str],
    extra: list[str],
) -> list[str]:
    """A pydantic model class for ``class_name`` over ``props``."""
    all_optional = bool(props) and not required
    text = description or f"``{class_name}`` (generated from openapi.json)."
    if all_optional:
        text += (
            "\n\nEvery field is optional, so this is a **sparse** body: what you leave "
            "out is left unchanged, and is omitted from the wire request entirely rather "
            "than sent as ``null`` (§27.4 rule 5)."
        )
    lines = [f"class {class_name}(ManagementModel):", *docstring(text, "    "), ""]
    lines.extend(extra)
    body_written = bool(extra)
    for pname in sorted(props):
        lines.extend(
            field_lines(
                pname,
                props[pname],
                required=pname in required,
                secret=pname in secrets,
            )
        )
        lines.append("")
        body_written = True
    if not body_written:
        lines.append("    # The server documents no fields on this schema.")
        lines.append("")
    return lines


def emit_models() -> str:
    """The whole ``models.py`` module."""
    secrets = sensitive_map()
    projections = projection_map()
    classes: list[str] = []
    out: list[str] = [
        BANNER,
        MODELS_HEADER,
        "from __future__ import annotations",
        "",
        "from typing import Annotated, Any, Literal",
        "",
        "from pydantic import Field, SecretStr, TypeAdapter",
        "",
        "from axiam_sdk.management._wire import ManagementModel",
    ]
    # isort (ruff I001) wants a single blank line between the import block and a
    # following assignment, and two before a `class`. Which one comes first here
    # depends on where the alphabet puts the schema, so decide it rather than assume.
    first = SCHEMAS[schema_closure()[0]]
    out.append("")
    if not ("enum" in first or discriminated(first)):
        out.append("")

    for name in schema_closure():
        schema = SCHEMAS[name]
        rname = pascal(name)
        if "enum" in schema:
            text = schema.get("description") or f"``{rname}`` (generated from openapi.json)."
            text += (
                "\n\nAn **open** enum. The trailing ``| str`` is what makes a value this "
                "SDK's copy of the spec does not list validate instead of raising -- "
                "CONTRACT §27.11 rule 1. A bare ``Literal`` is validated strictly by "
                "pydantic, so the next value the server adds would fail the *whole* "
                "response it arrived in, taking down every record on the page over one "
                "field of one of them. The listed members stay in the annotation because "
                "they are what a reader needs; what the widening removes is the claim "
                "that nothing else can occur."
            )
            members = [json.dumps(v) for v in schema["enum"]]
            oneline = f"{rname} = Literal[" + ", ".join(members) + "] | str"
            if len(oneline) <= 100:
                out.append(oneline)
            else:
                out.append(f"{rname} = (")
                out.append("    Literal[")
                out.extend(f"        {m}," for m in members)
                out.append("    ]")
                out.append("    | str")
                out.append(")")
            out.extend(field_doc(text, ""))
            out.append("")
            out.append("")
            continue

        union = discriminated(schema)
        if union:
            tag, arms = union
            arm_names: list[str] = []
            for value, payload in arms:
                arm = f"{rname}{pascal(value)}"
                arm_names.append(arm)
                if "$ref" in payload:
                    props, req, desc = flatten(payload["$ref"].split("/")[-1])
                else:
                    props = payload.get("properties") or {}
                    req = set(payload.get("required") or [])
                    desc = payload.get("description")
                tag_lines = [
                    f"    {safe(tag)}: Literal[{json.dumps(value)}]",
                    *field_doc(f"Discriminator: always ``{value}``."),
                    "",
                ]
                out.extend(
                    emit_model_class(
                        arm,
                        {k: v for k, v in props.items() if k != tag},
                        req - {tag},
                        desc or f"The ``{value}`` arm of :data:`{rname}`.",
                        set(),
                        tag_lines,
                    )
                )
                out.append("")
                classes.append(arm)
            text = schema.get("description") or (
                f"``{rname}`` -- a union discriminated by ``{tag}``."
            )
            out.append(f"{rname} = Annotated[")
            joined = "    " + " | ".join(arm_names) + ","
            if len(joined) <= 100:
                out.append(joined)
            else:
                for i, arm in enumerate(arm_names):
                    lead = "    " if i == 0 else "    | "
                    tail = "," if i == len(arm_names) - 1 else ""
                    out.append(f"{lead}{arm}{tail}")
            out.append(f'    Field(discriminator="{safe(tag)}"),')
            out.append("]")
            out.extend(field_doc(text, ""))
            out.append("")
            out.append(f"{rname}Adapter: TypeAdapter[{rname}] = TypeAdapter({rname})")
            out.extend(
                field_doc(
                    f"Validates a :data:`{rname}` payload.\n\nAn ``Annotated`` union alias "
                    f"has no ``model_validate`` of its own; this is built once at import "
                    f"rather than per call.",
                    "",
                )
            )
            out.append("")
            out.append("")
            continue

        props, required, description = flatten(name)
        props = dict(props)
        for add in projections.get(name, []):
            if add["name"] in props:
                continue
            required.discard(add["name"])
            props[add["name"]] = {
                "type": add.get("type"),
                "format": add.get("format"),
                "description": (
                    "Resolved by the list projection only.\n\n"
                    "The server resolves this for a whole page in one query, so it is "
                    "populated by the ``list`` operation and is ``None`` on ``get`` "
                    '(CONTRACT §27.11 rule 4). ``None`` there means "this read does not '
                    'carry it", not "there is nothing bound" -- the SDK does not issue '
                    "a second request to fill it in."
                ),
            }
        out.extend(
            emit_model_class(rname, props, required, description, secrets.get(name, set()), [])
        )
        out.append("")
        classes.append(rname)

    out.append("# Every annotation in this module is a string (`from __future__ import")
    out.append("# annotations`), so the forward references between these models are resolved")
    out.append("# here rather than lazily on first validation -- a broken reference should")
    out.append("# fail at import, where it names itself, not inside an unrelated request.")
    out.append("for _model in (")
    for cls in classes:
        out.append(f"    {cls},")
    out.append("):")
    out.append("    _model.model_rebuild()")
    out.append("")
    return "\n".join(out)


