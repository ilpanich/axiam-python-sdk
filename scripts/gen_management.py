def implicit_params(namespace: str, op: dict[str, Any]) -> set[str]:
    """Which of this operation's path params default from the client (§27.4 rule 3)."""
    names = {p["name"] for p in op["path_params"]}
    out: set[str] = set()
    if "org_id" in names:
        out.add("org_id")
    if "tenant_id" in names and namespace in IMPLICIT_TENANT_NAMESPACES:
        out.add("tenant_id")
    return out


def split_query(op: dict[str, Any]) -> tuple[list[Any], list[Any]]:
    """This operation's non-paging query params, split required / optional."""
    extra = extra_query_params(op)
    return [q for q in extra if q["required"]], [q for q in extra if not q["required"]]


def extra_query_params(op: dict[str, Any]) -> list[dict[str, Any]]:
    """Query parameters that become method arguments, rather than ``PageRequest``.

    ``offset`` and ``limit`` have always come from ``PageRequest``. ``search``
    joins them on paginated operations (CONTRACT §27.4 rule 4): the term is part
    of which page this is, and putting it on the page request rather than on each
    of the twenty generated ``list`` methods is what makes ``collect_pages`` carry
    it across the whole walk instead of filtering only the first request.

    The ``paginated`` guard matters. A *non*-paginated operation that grew a
    ``search`` parameter would have no ``PageRequest`` to carry it, so it keeps
    its own argument -- none exists in the registry today, and this is what keeps
    that from silently dropping the parameter if one ever does.
    """
    owned = ("offset", "limit", "search") if op["paginated"] else ("offset", "limit")
    return [q for q in op["query_params"] if q["name"] not in owned]


def projection_map() -> dict[str, list[dict[str, Any]]]:
    """Schema name -> the fields a list projection adds on top of it.

    ``certificates.list`` answers ``Certificate`` plus ``bound_service_account_id``,
    a graph edge the server resolves for the whole page in one query. CONTRACT
    §27.11 rule 4 lets an SDK carry that as an optional field on the base type,
    which is what this does: the field is ``None`` on ``get``, and the SDK never
    synthesizes it there with a second request.
    """
    out: dict[str, list[dict[str, Any]]] = {}
    for nsdef in REGISTRY["namespaces"].values():
        for op in nsdef["operations"].values():
            adds = op["response"].get("projected_fields")
            if not adds or not op["response"].get("schema"):
                continue
            base = op["response"]["schema"].removeprefix("[]")
            out.setdefault(base, []).extend(adds)
    return out


def filter_name(namespace: str, opname: str, optional: list[Any]) -> str | None:
    """The filter dataclass name for an operation with more than two filters."""
    return f"{pascal(namespace)}{pascal(opname)}Filter" if len(optional) > 2 else None


def is_union(name: str) -> bool:
    """Whether ``name`` is one of the internally-tagged unions on this surface."""
    return bool(discriminated(SCHEMAS.get(name, {})))


def response_expr(op: dict[str, Any], raw: str) -> tuple[str, str]:
    """The declared return type and the expression producing it from ``raw``."""
    kind, schema = op["response"]["kind"], op["response"]["schema"]
    if kind == "none":
        return "None", ""
    model = f"models.{pascal(schema)}"
    if is_union(schema):
        # A discriminated union is an `Annotated` alias, not a class: it has no
        # `.model_validate`, so pydantic validates it through a TypeAdapter,
        # built once at import in models.py rather than per call.
        adapter = f"models.{pascal(schema)}Adapter"
        if kind == "array":
            return (
                f"builtins.list[{model}]",
                f"[{adapter}.validate_python(item) for item in {raw} or []]",
            )
        if kind == "page":
            raise NotImplementedError(
                f"{op['summary']}: a paginated response whose item schema is a discriminated "
                f"union needs a page parser this generator does not emit. Add one to "
                f"_page.py and teach response_expr about it rather than shipping a call "
                f"to a helper that is not there."
            )
        return model, f"{adapter}.validate_python({raw})"
    if kind == "array":
        return (
            f"builtins.list[{model}]",
            f"[{model}.model_validate(item) for item in {raw} or []]",
        )
    if kind == "page":
        return f"Page[{model}]", f"page_of({raw}, {model})"
    return model, f"{model}.model_validate({raw})"


def operation_signature(
    namespace: str, opname: str, op: dict[str, Any]
) -> list[tuple[str, str, str]]:
    """This operation's caller-facing parameters as ``(name, annotation, default)``.

    Ordered so every parameter carrying a default follows every one that does
    not, which TypeScript tolerates and Python does not.
    """
    implicit = implicit_params(namespace, op)
    args: list[tuple[str, str, str]] = []
    for p in op["path_params"]:
        if p["name"] not in implicit:
            args.append((safe(p["name"]), "str", ""))
    required_q, optional_q = split_query(op)
    for q in required_q:
        args.append((safe(q["name"]), "str", ""))
    if op["request_body"] == "schema":
        args.append(("body", f"models.{pascal(op['request_schema'])}", ""))
    elif op["request_body"] == "untyped":
        args.append(("body", "Any", ""))
    fname = filter_name(namespace, opname, optional_q)
    if fname:
        args.append(("filter", f"{fname} | None", "None"))
    else:
        for q in optional_q:
            args.append((safe(q["name"]), "str | None", "None"))
    if op["paginated"]:
        args.append(("page", "PageRequest | None", "None"))
    return args


def emit_call_builder(namespace: str, opname: str, op: dict[str, Any]) -> list[str]:
    """The shared ``ManagementCall`` builder both handles use for one operation."""
    canonical = f"{namespace}.{opname}"
    implicit = implicit_params(namespace, op)
    args = operation_signature(namespace, opname, op)
    params = ["client: _AxiamClientBase", "scope: NamespaceScope"]
    params += [f"{n}: {t}" + (f" = {d}" if d else "") for n, t, d in args]

    prelude: list[str] = []
    route = op["path"]
    for p in op["path_params"]:
        name = p["name"]
        if name in implicit:
            fn = "resolve_org" if name == "org_id" else "resolve_tenant"
            prelude.append(f'    {safe(name)} = {fn}(client, scope, "{canonical}")')
            route = route.replace(f"{{{name}}}", f"{{{safe(name)}}}")
        elif p.get("format") == "uuid":
            prelude.append(
                f'    {safe(name)} = require_uuid({safe(name)}, "{name}", "{canonical}")'
            )
            route = route.replace(f"{{{name}}}", f"{{{safe(name)}}}")
        else:
            prelude.append(f'    {safe(name)} = quote({safe(name)}, safe="")')
            route = route.replace(f"{{{name}}}", f"{{{safe(name)}}}")

    required_q, optional_q = split_query(op)
    fname = filter_name(namespace, opname, optional_q)
    query: list[str] = []
    if op["paginated"]:
        query.append("**page_query(page)")
    for q in required_q:
        query.append(f'"{q["name"]}": {safe(q["name"])}')
    for q in optional_q:
        src = f"(filter.{safe(q['name'])} if filter else None)" if fname else safe(q["name"])
        query.append(f'"{q["name"]}": {src}')

    if op["request_body"] == "schema":
        body_expr = "body.to_wire()"
    elif op["request_body"] == "untyped":
        body_expr = "body"
    else:
        body_expr = None

    lines = [f"def _call_{safe(opname)}(", *[f"    {p}," for p in params], ") -> ManagementCall:"]
    lines.extend(
        docstring(
            f"Build the ``{canonical}`` call.\n\nShared by the sync and async handles so the "
            f"path, query and body are decided in exactly one place.",
            "    ",
        )
    )
    lines.extend(prelude)
    lines.append("    return ManagementCall(")
    lines.append(f'        operation="{canonical}",')
    lines.append(f'        method="{op["method"]}",')
    lines.append(f'        path_template="{op["path"]}",')
    lines.append(f'        path=f"{route}",' if "{" in route else f'        path="{route}",')
    if query:
        oneline = "        query={" + ", ".join(query) + "},"
        if len(oneline) <= 100:
            lines.append(oneline)
        else:
            lines.append("        query={")
            lines.extend(f"            {entry}," for entry in query)
            lines.append("        },")
    if body_expr:
        lines.append(f"        body={body_expr},")
    lines.append("    )")
    lines.append("")
    lines.append("")
    return lines


def operation_doc(op: dict[str, Any]) -> str:
    """The docstring for one generated operation method."""
    text = f"``{op['method']} {op['path']}``"
    if op["update_style"] == "replace":
        text += (
            "\n\n**This is a replacement, not a patch** (§27.4 rule 5). Every field of the "
            "body is required, and what you do not carry over from a prior read is not "
            "preserved -- it is overwritten. Read first, change the field you mean, send "
            "the whole thing back."
        )
    if op["sensitive_response_fields"]:
        joined = ", ".join(f"``{f}``" for f in op["sensitive_response_fields"])
        text += (
            f"\n\n**Returns secret material, once.** {joined} is returned by this call and "
            f"by no other; no later ``get`` will return it again, and the ``get`` projection "
            f"has no field where it was. Discarding the result destroys the credential "
            f"(§27.5 rule 3)."
        )
    if op["method"] != "GET":
        text += (
            "\n\nNot retried on failure (§27.4 rule 8): every write on this surface is "
            "issued exactly once, including the ones that look idempotent."
        )
    return text


def signature_lines(
    adef: str, method: str, args: list[tuple[str, str, str]], ret: str
) -> list[str]:
    """A ``def`` line for ``method``, wrapped across lines when it will not fit."""
    rendered = [f"{n}: {t}" + (f" = {d}" if d else "") for n, t, d in args]
    oneline = f"    {adef} {method}(self" + "".join(f", {r}" for r in rendered) + f") -> {ret}:"
    if len(oneline) <= 100:
        return [oneline]
    return [
        f"    {adef} {method}(",
        "        self,",
        *[f"        {r}," for r in rendered],
        f"    ) -> {ret}:",
    ]


def emit_handle(namespace: str, nsdef: dict[str, Any], *, is_async: bool) -> list[str]:
    """One namespace handle class, in its sync or async form."""
    cls = ("Async" if is_async else "") + f"{pascal(namespace)}Api"
    client_type = "AsyncAxiamClient" if is_async else "AxiamClient"
    ops = nsdef["operations"]
    has_org = any("org_id" in implicit_params(namespace, o) for o in ops.values())
    has_tenant = any("tenant_id" in implicit_params(namespace, o) for o in ops.values())
    adef, aw = ("async def", "await ") if is_async else ("def", "")
    send = "send_management_async" if is_async else "send_management"
    collect = "collect_pages_async" if is_async else "collect_pages"

    lines = [f"class {cls}:"]
    lines.extend(
        docstring(
            f"The ``{namespace}`` namespace handle"
            + (", async form." if is_async else ".")
            + f"\n\n{nsdef['doc']}\n\nAcquiring one performs no I/O and allocates nothing "
            f"meaningful (§27.2 rule 1); it holds the client and cannot be constructed "
            f"without one.",
            "    ",
        )
    )
    lines.append("")
    lines.append(
        f"    def __init__("
        f"self, client: {client_type}, scope: NamespaceScope | None = None"
        f") -> None:"
    )
    lines.extend(
        docstring("Bind the handle to ``client``; reached as a client property.", "        ")
    )
    lines.append("        self._client = client")
    lines.append("        self._scope = scope or NamespaceScope()")
    lines.append("")

    if has_org:
        lines.append(f"    def in_org(self, org_id: str) -> {cls}:")
        lines.extend(
            docstring(
                "Address a different organization than the client's own.\n\n§27.4 rule 3: the "
                "client's ``org_id`` is the default, and a platform-admin token legitimately "
                "overrides it. Returns a new handle; the original is unchanged.",
                "        ",
            )
        )
        lines.append(f"        return {cls}(self._client, self._scope.with_org(org_id))")
        lines.append("")
    if has_tenant:
        lines.append(f"    def for_tenant(self, tenant_id: str) -> {cls}:")
        lines.extend(
            docstring(
                "Address a different tenant than the client's own (§27.4 rule 3).\n\nReturns a "
                "new handle; the original is unchanged.",
                "        ",
            )
        )
        lines.append(f"        return {cls}(self._client, self._scope.with_tenant(tenant_id))")
        lines.append("")

    for opname, op in ops.items():
        args = operation_signature(namespace, opname, op)
        method = safe(opname)
        ret, expr = response_expr(op, "raw")
        forward = ", ".join(n for n, _, _ in args)
        call = f"_call_{method}(self._client, self._scope{', ' + forward if forward else ''})"

        lines.extend(signature_lines(adef, method, args, ret))
        lines.extend(docstring(operation_doc(op), "        "))
        assign = "" if ret == "None" else "raw = "
        lines.append(f"        {assign}{aw}{send}(")
        lines.append("            self._client,")
        lines.append(f"            {call},")
        lines.append("        )")
        if ret != "None":
            lines.append(f"        return {expr}")
        lines.append("")

        if op["paginated"]:
            lead = [(n, t, d) for n, t, d in args if n != "page"]
            lead_fwd = "".join(f"{n}, " for n, _, _ in lead)
            inner = ret[len("Page[") : -1]
            # Same shadowing as the array case above: `list` is a method here.
            lines.extend(
                signature_lines(
                    adef,
                    f"{method}_all",
                    [*lead, ("start", "PageRequest | None", "None")],
                    f"builtins.list[{inner}]",
                )
            )
            lines.extend(
                docstring(
                    f"Walk ``{namespace}.{opname}`` to exhaustion, concatenating every page."
                    "\n\nThe auto-paging form §27.4 rule 4 requires. It stops on an empty page "
                    "even if ``total`` disagrees, so a misreporting server costs one wasted "
                    "request rather than an unbounded loop.",
                    "        ",
                )
            )
            lines.append(
                f"        return {aw}{collect}(start, lambda p: self.{method}({lead_fwd}p))"
            )
            lines.append("")
    return lines


def emit_filters(namespace: str, nsdef: dict[str, Any]) -> list[str]:
    """Filter dataclasses for the operations carrying more than two optional filters."""
    out: list[str] = []
    for opname, op in nsdef["operations"].items():
        _, optional = split_query(op)
        name = filter_name(namespace, opname, optional)
        if not name:
            continue
        out.append("@dataclass(frozen=True)")
        out.append(f"class {name}:")
        out.extend(
            docstring(
                f"Optional filters for ``{namespace}.{opname}``.\n\nSix loose optional "
                f"arguments is a call site a reader cannot check and a refactor silently "
                f"reorders, so they travel as one object.",
                "    ",
            )
        )
        out.append("")
        for q in optional:
            out.append(f"    {safe(q['name'])}: str | None = None")
            out.extend(field_doc(f"Filter on ``{q['name']}``."))
            out.append("")
        out.append("")
    return out


def emit_namespace(namespace: str, nsdef: dict[str, Any]) -> str:
    """The whole ``ops/<namespace>.py`` module."""
    body: list[str] = []
    body.extend(emit_filters(namespace, nsdef))
    for opname, op in nsdef["operations"].items():
        body.extend(emit_call_builder(namespace, opname, op))
    body.extend(emit_handle(namespace, nsdef, is_async=False))
    body.append("")
    body.extend(emit_handle(namespace, nsdef, is_async=True))
    rendered = "\n".join(body)

    page_names = [
        n
        for n in ("collect_pages_async", "collect_pages", "page_of", "page_query")
        if n in rendered
    ]
    page_types = [n for n in ("PageRequest", "Page") if n in rendered]
    scope_names = [n for n in ("require_uuid", "resolve_org", "resolve_tenant") if n in rendered]

    imports = ["from __future__ import annotations", ""]
    typing_names = [n for n in ("Any",) if f": {n}" in rendered or f"[{n}]" in rendered]
    plain: list[str] = []
    stdlib: list[str] = []
    if "builtins." in rendered:
        # Every namespace handle whose canonical operation set includes `list`
        # shadows the builtin inside its own class body, so an annotation like
        # `list[Resource]` would resolve to the method rather than the type.
        # Qualifying it is the fix that keeps the operation named what §27.1
        # names it.
        plain.append("import builtins")
    if "@dataclass" in rendered:
        stdlib.append("from dataclasses import dataclass")
    if typing_names:
        stdlib.append("from typing import TYPE_CHECKING, " + ", ".join(typing_names))
    else:
        stdlib.append("from typing import TYPE_CHECKING")
    if "quote(" in rendered:
        stdlib.append("from urllib.parse import quote")
    # isort puts every `import x` above every `from x import y`, so the two
    # groups are sorted separately rather than as one list of strings.
    imports.extend(sorted(plain))
    imports.extend(sorted(stdlib))
    imports.append("")
    if "models." in rendered:
        imports.append("from axiam_sdk.management import models")
    if page_types or page_names:
        merged = sorted(page_types + page_names)
        imports.append(
            "from axiam_sdk.management._page import (\n"
            + "".join(f"    {n},\n" for n in merged)
            + ")"
        )
    imports.append(
        "from axiam_sdk.management._request import (\n"
        "    ManagementCall,\n"
        "    send_management,\n"
        "    send_management_async,\n"
        ")"
    )
    scope_import = ["NamespaceScope", *scope_names]
    imports.append(
        "from axiam_sdk.management._scope import (\n"
        + "".join(f"    {n},\n" for n in sorted(scope_import))
        + ")"
    )
    imports.append("")
    imports.append("if TYPE_CHECKING:  # pragma: no cover - typing only")
    imports.append("    from axiam_sdk._async_client import AsyncAxiamClient")
    imports.append("    from axiam_sdk._client import AxiamClient, _AxiamClientBase")
    imports.append("")

    header = [BANNER.rstrip("\n"), ""]
    header.extend(
        docstring(f"The ``{namespace}`` management namespace (CONTRACT §27.1).\n\n{nsdef['doc']}")
    )
    header.append("")
    return "\n".join([*header, *imports, "", rendered]).rstrip("\n") + "\n"


